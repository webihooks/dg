function generateAgreementContent($pdf, $user_data, $subscription_data) {
    $pdf->SetFont('helvetica', '', 10);
    $pdf->SetTextColor(51, 51, 51);

    // Use start_date from subscriptions table for effective date
    $effective_date = 'N/A';
    if (!empty($subscription_data['start_date'])) {
        $effective_date = date('jS \d\a\y \o\f F, Y', strtotime($subscription_data['start_date']));
    } else {
        $effective_date = date('jS \d\a\y \o\f F, Y');
    }

    // Get package price from packages table
    $package_price = 'Rs.9,999';
    if (!empty($subscription_data['package_price'])) {
        $package_price = 'Rs.' . number_format($subscription_data['package_price']);
    }

    // Effective Date
    $pdf->MultiCell(0, 10, "This Service Agreement (\"Agreement\") is entered into on this {$effective_date} (\"Effective Date\"), by and between:", 0, 'L');
    $pdf->Ln(2);

    $pdf->SetFont('helvetica', 'B', 10);
    $pdf->MultiCell(0, 10, "DeeGeeCard\nA product of Digital Growth Solutions\nRegistered Address: Mira Road, Thane, Maharashtra\nContact | support@deegeecard.com\n(Hereinafter referred to as the \"Service Provider\")", 0, 'L');
    $pdf->Ln(2);

    $pdf->SetFont('helvetica', '', 10);
    $pdf->MultiCell(0, 10, "AND", 0, 'C');
    $pdf->Ln(2);

    // Client Information
    $client_name = $user_data['business_name'] ?: $user_data['name'];
    $client_address = $user_data['business_address'] ?: $user_data['address'];
    $owner_name = $user_data['name'];
    $phone = $user_data['phone'];
    $email = $user_data['email'];
    $designation = $user_data['designation'] ?: 'Owner/Manager';

    $pdf->SetFont('helvetica', 'B', 10);
    $pdf->MultiCell(0, 10, "Client/Restaurant Name: {$client_name}\nAddress: {$client_address}\n{$designation} Name: {$owner_name}\nPhone: {$phone}   |   Email: {$email}\n(Hereinafter referred to as the \"Client\")", 0, 'L');

    $pdf->Ln(6);

    // Agreement Sections - Compact version to fit in 2 pages
    $sections = [
        '1. Purpose' => "The purpose of this Agreement is to define the terms under which the Service Provider will offer the DeeGeeCard restaurant digital platform and related services to the Client.",
        
        '2. Services Provided' => "The Service Provider agrees to provide:\n• Restaurant Ordering Website fully branded\n• Android Mobile Application\n• Admin Management Application\n• 1000 QR Code Visiting Cards\n• Bulk WhatsApp Marketing Panel\n• Direct Payment Gateway Integration\n• Google, Instagram, Facebook, YouTube Integrations\n• Technical Setup within same day",
        
        '3. Term and Renewal' => "Valid for one year from Effective Date.\nRenewal: {$package_price}/year (subject to revision).\nNo refunds after activation.",
        
        '4. Fees and Payments' => "Client agrees to pay {$package_price}/year.\nPayment in full, in advance.\nService Provider may revise pricing upon renewal.",
        
        '5. Responsibilities of the Client' => "Client agrees to:\n• Provide accurate restaurant details\n• Ensure legal, original content\n• Manage customer orders & disputes\n• Approve artwork timely\n• Use system responsibly",
        
        '6. Ownership & Intellectual Property' => "DeeGeeCard platform rights remain with Service Provider.\nClient receives limited license during subscription.\nClient's brand assets remain Client's property.",
        
        '7. Direct Payments' => "Customer payments go directly to Client's bank account.\nService Provider not responsible for payment issues.",
        
        '8. Data & Confidentiality' => "Customer data belongs to Client.\nService Provider won't misuse or share data.",
        
        '9. Support & Maintenance' => "Technical support via WhatsApp, email, or call.\nUpdates at Service Provider's discretion.",
        
        '10. Limitations & Liability' => "Service Provider not responsible for:\n• Restaurant operations & quality\n• Customer reviews\n• Internet/API outages\nMax liability: fees paid by Client",
        
        '11. Termination' => "Service Provider may terminate if Client:\n• Engages in illegal activity\n• Misuses platform\n• Fails to comply with terms\nNo refunds upon termination.",
        
        '12. Indemnity' => "Client agrees to indemnify Service Provider from claims arising from restaurant operations or platform misuse.",
        
        '13. Governing Law' => "Governed by laws of India. Jurisdiction: Mumbai courts."
    ];

    // Add sections to PDF with compact spacing
    foreach ($sections as $title => $content) {
        // Check if we need a new page
        if ($pdf->GetY() > 240) {
            $pdf->AddPage();
        }
        
        $pdf->SetFont('helvetica', 'B', 11);
        $pdf->SetFillColor(255, 233, 220);
        $pdf->Cell(0, 8, $title, 0, 1, 'L', true);
        $pdf->SetFont('helvetica', '', 9);
        $pdf->MultiCell(0, 6, $content, 0, 'L');
        $pdf->Ln(4);
    }
}
