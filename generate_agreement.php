<?php
// Start with output buffering to catch any stray output
ob_start();

session_start();
date_default_timezone_set('Asia/Kolkata');
// Check authentication first
if (!isset($_SESSION['user_id'])) {
    header("Location: login.php");
    exit();
}

require_once 'config.php';
require_once 'db_connection.php';

$user_id = $_SESSION['user_id'];

// Fetch user and business details
$user_sql = "SELECT u.name, u.email, u.phone, u.address, 
                    b.business_name, b.business_address, b.designation
             FROM users u 
             LEFT JOIN business_info b ON u.id = b.user_id 
             WHERE u.id = ?";
$stmt = $conn->prepare($user_sql);
$stmt->bind_param("i", $user_id);
$stmt->execute();
$result = $stmt->get_result();
$user_data = $result->fetch_assoc();
$stmt->close();

// Fetch current subscription with package price
$subscription_sql = "SELECT p.name as package_name, s.start_date, p.price as package_price
                     FROM subscriptions s 
                     JOIN packages p ON s.package_id = p.id 
                     WHERE s.user_id = ? AND s.status = 'active' 
                     ORDER BY s.start_date DESC LIMIT 1";
$stmt_sub = $conn->prepare($subscription_sql);
$stmt_sub->bind_param("i", $user_id);
$stmt_sub->execute();
$subscription_result = $stmt_sub->get_result();
$subscription_data = $subscription_result->fetch_assoc();
$stmt_sub->close();

$conn->close();

// Clear any output that might have been generated
ob_clean();

// Check if TCPDF exists, if not use a simple approach
if (file_exists('tcpdf/tcpdf.php')) {
    generateWithTCPDF($user_data, $subscription_data);
} else {
    generateSimplePDF($user_data, $subscription_data);
}

function generateWithTCPDF($user_data, $subscription_data) {
    require_once('tcpdf/tcpdf.php');

    // Create custom TCPDF class to handle background on all pages
    class CustomTCPDF extends TCPDF {
        // Page header
        public function Header() {
            // Set background color for all pages
            $this->SetFillColor(255, 233, 220);
            $this->Rect(0, 0, $this->getPageWidth(), $this->getPageHeight(), 'F');
            
            // Add logo on ALL pages
            $logo_path = 'images/deegeecard_logo.png';
            if (file_exists($logo_path)) {
                // Bigger logo - 3x size (90 width instead of 30)
                // Calculate center position: (page width - logo width) / 2
                $page_width = $this->getPageWidth();
                $logo_width = 90;
                $x_position = ($page_width - $logo_width) / 2;
                
                // Reduced margin bottom from logo (from 55 to 35 - 50% decrease)
                $this->Image($logo_path, $x_position, 15, 90, 0, 'PNG', '', 'T', false, 300, '', false, false, 0, false, false, false);
                $this->SetY(35); // Reduced from 55 to 35 (50% decrease)
            } else {
                $this->SetY(25);
            }
            
            // Title on first page only
            if ($this->page == 1) {
                $this->SetFont('helvetica', 'B', 20);
                $this->SetTextColor(51, 51, 51);
                $this->Cell(0, 10, 'DeeGeeCard – Service Agreement', 0, 1, 'C');
                $this->Ln(5);
            }
        }
        
        // Page footer
        public function Footer() {
            // Position closer to bottom (reduced from -25 to -20)
            $this->SetY(-35);
            $this->SetFont('helvetica', 'I', 8);
            $this->SetTextColor(128, 128, 128);
            
            // Add the new agreement text
            $this->Cell(0, 6, 'This is a system-generated agreement and shall be considered valid without a physical signature, unless expressly requested by either party.', 0, 1, 'C');
            
            // Page info with reduced margin (moved up closer to the agreement text)
            $this->Cell(0, 6, 'Page ' . $this->getAliasNumPage() . ' of ' . $this->getAliasNbPages() . ' - Generated by DeeGeeCard System on ' . date('d/m/Y H:i:s'), 0, 0, 'C');
            
            // Add small logo in footer on all pages
            if (file_exists('images/deegeecard_logo.png')) {
                $this->Image('images/deegeecard_logo.png', 85, $this->GetY() + 8, 30, 0, 'PNG', '', 'T', false, 300, '', false, false, 0, false, false, false);
            }
        }
    }

    // Create new PDF document with custom class
    $pdf = new CustomTCPDF(PDF_PAGE_ORIENTATION, PDF_UNIT, PDF_PAGE_FORMAT, true, 'UTF-8', false);

    // Set document information
    $pdf->SetCreator('DeeGeeCard');
    $pdf->SetAuthor('DeeGeeCard');
    $pdf->SetTitle('Service Agreement');

    // Remove default header/footer (we're using custom ones)
    $pdf->setPrintHeader(true);
    $pdf->setPrintFooter(true);

    // Set margins - reduced top margin due to decreased logo margin
    $pdf->SetMargins(15, 50, 15); // Reduced from 70 to 50 (accommodates reduced logo margin)
    $pdf->SetAutoPageBreak(true, 30);

    // Add first page
    $pdf->AddPage();

    // Agreement content
    generateAgreementContent($pdf, $user_data, $subscription_data);

    // Output PDF
    $client_name = $user_data['business_name'] ?: $user_data['name'];
    $filename = 'DeeGeeCard_Service_Agreement_' . preg_replace('/[^a-zA-Z0-9]/', '_', $client_name) . '_' . date('Y-m-d') . '.pdf';
    
    $pdf->Output($filename, 'D');
    exit;
}

